import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const output = 'apps/compass/web/src/app/core/supabase/database.types.ts';
const configPath = 'supabase/config.toml';
const expectedApiSchemas = ['public', 'graphql_public', 'shared', 'land'];
const privateSchemas = ['universe', 'geo', 'canon'];

mkdirSync('apps/compass/web/src/app/core/supabase', { recursive: true });

const config = readFileSync(configPath, 'utf8');
const apiSectionMatch = config.match(/\[api\]([\s\S]*?)(?=\n\[[^\]]+\]|$)/);

if (!apiSectionMatch) {
  throw new Error('supabase/config.toml is missing [api] section');
}

const schemasMatch = apiSectionMatch[1].match(/^\s*schemas\s*=\s*\[([^\]]*)\]/m);

if (!schemasMatch) {
  throw new Error('supabase/config.toml [api] section is missing schemas');
}

const configuredApiSchemas = [...schemasMatch[1].matchAll(/["']([^"']+)["']/g)].map(
  (match) => match[1],
);

if (
  configuredApiSchemas.length !== expectedApiSchemas.length ||
  configuredApiSchemas.some((schema, index) => schema !== expectedApiSchemas[index])
) {
  throw new Error(
    `Unexpected Data API schema config. Expected: ${expectedApiSchemas.join(', ')}. Actual: ${configuredApiSchemas.join(', ')}`,
  );
}

for (const privateSchema of privateSchemas) {
  if (configuredApiSchemas.includes(privateSchema)) {
    throw new Error(`Private SIDEWORLD schema exposed in Data API config: ${privateSchema}`);
  }
}

const generated = execFileSync(
  'npx',
  ['--yes', 'supabase@2.119.0', 'gen', 'types', 'typescript', '--local'],
  {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    shell: process.platform === 'win32',
  },
);

if (!generated.includes('export type Database') && !generated.includes('export interface Database')) {
  throw new Error('Supabase type generation did not produce a Database type');
}

const schemaKeyPattern = (schema) =>
  new RegExp(`^\\s*["']?${schema}["']?\\s*:\\s*\\{`, 'm');

for (const required of ['shared', 'land']) {
  if (!schemaKeyPattern(required).test(generated)) {
    throw new Error(`Generated database types are missing required application schema: ${required}`);
  }
}

for (const privateSchema of privateSchemas) {
  if (schemaKeyPattern(privateSchema).test(generated)) {
    throw new Error(`Private SIDEWORLD schema leaked into client database types: ${privateSchema}`);
  }
}

writeFileSync(
  output,
  `// Generated by npm run db:types from Data API schemas declared in supabase/config.toml: ${configuredApiSchemas.join(', ')}. Do not edit manually.\n${generated}`,
);
