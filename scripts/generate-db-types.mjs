import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';

const output = 'apps/compass/web/src/app/core/supabase/database.types.ts';
const apiSchemas = ['public', 'graphql_public', 'shared', 'land'];

mkdirSync('apps/compass/web/src/app/core/supabase', { recursive: true });

const generated = execFileSync(
  'npx',
  [
    '--yes',
    'supabase@2.119.0',
    'gen',
    'types',
    'typescript',
    '--local',
    '--schema',
    apiSchemas.join(','),
  ],
  {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    shell: process.platform === 'win32',
  },
);

for (const required of ['public', 'shared', 'land']) {
  if (!new RegExp(`^\\s*${required}\\s*:\\s*\\{`, 'm').test(generated)) {
    throw new Error(`Generated database types are missing exposed schema: ${required}`);
  }
}

for (const privateSchema of ['universe', 'geo', 'canon']) {
  if (new RegExp(`^\\s*${privateSchema}\\s*:\\s*\\{`, 'm').test(generated)) {
    throw new Error(`Private SIDEWORLD schema leaked into client database types: ${privateSchema}`);
  }
}

writeFileSync(
  output,
  `// Generated by npm run db:types from explicit Data API schemas: ${apiSchemas.join(', ')}. Do not edit manually.\n${generated}`,
);
