import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';

const output = 'apps/compass/web/src/app/core/supabase/database.types.ts';

mkdirSync('apps/compass/web/src/app/core/supabase', { recursive: true });
const generated = execFileSync(
  'npx',
  ['supabase', 'gen', 'types', 'typescript', '--local'],
  { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], shell: process.platform === 'win32' }
);
writeFileSync(output, `// Generated by npm run db:types. Do not edit manually.\n${generated}`);